-- เพิ่มฟิลด์ "เพศ" จริงให้ตาราง teachers แทนการเดาจากคำนำหน้าชื่อ (เดิมระบบใช้ getTeacherGender()
-- เดาจาก "นาย"/"Mr."/"Kru" ที่ขึ้นต้นชื่อ ถ้าครูคนไหนไม่มีคำนำหน้าตรงเงื่อนไข ระบบจะเข้าใจผิดว่าเป็น
-- ผู้หญิงเสมอ ทำให้การลา/รายงานเวรของครูคนนั้นถูกส่งไปเข้าคิวหัวหน้าเวรฝั่งผิด — เจอจริงกับ
-- หัวหน้าเวรวันศุกร์ที่ไม่เห็นข้อมูลแจ้งลา/รายงานย้อนหลังของลูกเวรตัวเอง)
--
-- รันใน Supabase SQL Editor ได้อย่างปลอดภัย หากมีคอลัมน์อยู่แล้วจะไม่สร้างซ้ำ

ALTER TABLE teachers
  ADD COLUMN IF NOT EXISTS gender TEXT;

-- Backfill ครูเดิมทุกคนด้วยตรรกะเดิมที่ระบบเคยใช้ (เดาจากคำนำหน้าชื่อ) เพื่อไม่ให้พฤติกรรม
-- เปลี่ยนกะทันหันสำหรับครูที่เดาถูกอยู่แล้ว — จากนั้นแอดมินค่อยเข้าไปแก้ไขเฉพาะคนที่เดาผิด
-- ได้จากหน้า "ข้อมูลบุคลากร" > แก้ไข > เลือกเพศ
UPDATE teachers
SET gender = CASE
  WHEN id IN ('admin', 'chief', 'director', '1087') THEN 'ชาย'
  WHEN name ILIKE 'นาย%' OR name ILIKE 'MR.%' OR name ILIKE 'Kru%' THEN 'ชาย'
  ELSE 'หญิง'
END
WHERE gender IS NULL;
